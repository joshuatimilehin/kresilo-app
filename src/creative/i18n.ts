export const messages: Record<Locale, Record<MessageKey, string>> = { en, es, ar };

/** Looks up a message. A missing translation falls back to English, never to a key. */
export function translate(locale: Locale, key: MessageKey, vars: Record<string, string | number> = {}): string {
  const text = messages[locale]?.[key] ?? en[key];
  return text.replace(/\{(\w+)\}/g, (whole, name) => (name in vars ? String(vars[name]) : whole));
}

export function formatDate(locale: Locale, iso: string): string {
  return new Date(iso).toLocaleString(locale, {
    month: "short",
    day: "numeric",
    hour: "numeric",
    minute: "2-digit",
  });
}

export const formatNumber = (locale: Locale, n: number) => new Intl.NumberFormat(locale).format(n);
