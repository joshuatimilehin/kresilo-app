/**
 * Interface language (issue #49). Pure: the dictionary, the lookup and the
 * locale formatting, so the provider and the screens stay thin and the rules
 * are tested without a browser.
 *
 * Scope today: the shell (navigation), sharing, comments and the team page.
 * Everything else is still English. Maker-written text is never translated:
 * it stays in the language it was written in. Spanish and Arabic are
 * machine-assisted translations that a native reader has not checked yet, and
 * the language switch says so.
 */
export const locales = [
  { code: "en", name: "English", dir: "ltr" },
  { code: "es", name: "Español", dir: "ltr" },
  { code: "ar", name: "العربية", dir: "rtl" },
] as const;
export type Locale = (typeof locales)[number]["code"];
export const DEFAULT_LOCALE: Locale = "en";

export const isLocale = (value: unknown): value is Locale =>
  locales.some((l) => l.code === value);

export const dirOf = (locale: Locale): "ltr" | "rtl" =>
  locales.find((l) => l.code === locale)?.dir ?? "ltr";

/** The best match for a browser's language list, falling back to English. */
export function pickLocale(preferred: readonly string[]): Locale {
  for (const tag of preferred) {
    const base = tag.toLowerCase().split("-")[0];
    if (isLocale(base)) return base;
  }
  return DEFAULT_LOCALE;
}

